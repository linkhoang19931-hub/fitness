export const normalize = (s) =>
  s
    .toLowerCase()
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .replace(/đ/g, 'd');

const slug = (s) => normalize(s).replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

export const FOODS = Object.entries(DATA).flatMap(([group, rows]) =>
  rows.map(([name, protein, fat, carbs, opt = {}]) => ({
    id: opt.id || slug(name),
    group,
    name,
    protein,
    fat,
    carbs,
    src: opt.src || DEFAULT_SRC[group] || 'ước',
    search: normalize(`${name} ${opt.kw || ''}`),
  }))
);

export const FOOD_BY_ID = Object.fromEntries(FOODS.map((f) => [f.id, f]));

