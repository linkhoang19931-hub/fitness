// Tìm món: mọi từ khoá đều phải khớp (không phân biệt dấu); ưu tiên tên bắt đầu bằng từ khoá
export function searchFoods(query, list = FOODS, limit = 50) {
  const q = normalize(query.trim());
  if (!q) return list.slice(0, limit);
  const words = q.split(/\s+/);
  return list
    .filter((f) => words.every((w) => (f.search || normalize(f.name)).includes(w)))
    .sort((a, b) => {
      const sa = normalize(a.name).startsWith(q) ? 0 : 1;
      const sb = normalize(b.name).startsWith(q) ? 0 : 1;
      return sa - sb || a.name.length - b.name.length;
    })
    .slice(0, limit);
}
